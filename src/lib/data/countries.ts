import type { Country, TaxModel } from "@/lib/types";

// Illustrative reference data (approximate 2025/2026-era figures) used to
// demonstrate the calculation model. See /methodology for sourcing notes and
// limitations — this is not a substitute for official economic datasets.

function flagEmoji(code: string): string {
  return String.fromCodePoint(
    ...code
      .toUpperCase()
      .split("")
      .map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65)
  );
}

function flat(rate: number): TaxModel {
  return { type: "flat", rate };
}

// Compact builder for the broad long tail of countries: a single flat rate
// approximates overall personal income tax burden (top/typical marginal
// rate), rather than authoring full brackets for every country.
function c(
  code: string,
  name: string,
  currencyCode: string,
  currencySymbol: string,
  fxToUsd: number,
  pppFactor: number,
  housingIndex: number,
  livingIndex: number,
  flatTaxRate: number
): Country {
  return {
    code,
    name,
    currencyCode,
    currencySymbol,
    flag: flagEmoji(code),
    fxToUsd,
    pppFactor,
    housingIndex,
    livingIndex,
    tax: flat(flatTaxRate),
    dataYear: 2026,
  };
}

